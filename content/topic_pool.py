def _load_recent() -> List[str]:
    """Load recently used topics."""
    try:
        with open(RECENT_TOPICS_FILE, "r", encoding="utf-8") as f:
            data = json.load(f)
            if isinstance(data, list):
                return data
    except (FileNotFoundError, json.JSONDecodeError):
        pass
    return []


def _save_recent(topics: List[str]) -> None:
    """Save recently used topics."""
    with open(RECENT_TOPICS_FILE, "w", encoding="utf-8") as f:
        json.dump(topics[-MAX_RECENT_TOPICS:], f, ensure_ascii=False, indent=2)


def _extract_keywords(topic: str) -> set:
    """Extract significant keywords from a topic string."""
    words = topic.lower().replace(":", " ").replace(",", " ").replace("—", " ").split()
    return {w for w in words if len(w) > 4}


def _is_too_similar(topic: str, recent: List[str]) -> bool:
    """Check if topic is too similar to any recently used topic."""
    topic_kw = _extract_keywords(topic)
    for recent_topic in recent[-10:]:
        recent_kw = _extract_keywords(recent_topic)
        overlap = topic_kw & recent_kw
        if len(overlap) >= 3:
            return True
    return False


