def get_next_topic(content_type: str) -> str:
    """Get the next topic using round-robin with cross-type deduplication."""
    pool = TOPIC_POOL.get(content_type, TOPIC_POOL["micro_protocol"])
    state = _load_state()
    recent = _load_recent()
    index = state.get(content_type, 0)

    for _ in range(len(pool)):
        if index >= len(pool):
            index = 0
            random.shuffle(pool)

        topic = pool[index]
        index += 1

        if not _is_too_similar(topic, recent):
            state[content_type] = index
            _save_state(state)
            recent.append(topic)
            _save_recent(recent)
            logger.info("Topic assigned [%s] #%d: %s", content_type, index, topic[:50])
            return topic

        logger.info("Skipping similar topic [%s]: %s", content_type, topic[:50])

    topic = pool[index - 1]
    state[content_type] = index
    _save_state(state)
    recent.append(topic)
    _save_recent(recent)
    logger.info("Topic assigned (forced) [%s] #%d: %s", content_type, index, topic[:50])
    return topic


