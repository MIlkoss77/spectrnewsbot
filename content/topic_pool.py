def _load_state() -> Dict[str, int]:
    """Load the current rotation index for each content type."""
    try:
        with open(POOL_STATE_FILE, "r", encoding="utf-8") as f:
            data = json.load(f)
            if isinstance(data, dict):
                return data
    except (FileNotFoundError, json.JSONDecodeError):
        pass
    return {}


def _save_state(state: Dict[str, int]) -> None:
    """Save the rotation state."""
    with open(POOL_STATE_FILE, "w", encoding="utf-8") as f:
        json.dump(state, f, ensure_ascii=False, indent=2)


def get_next_topic(content_type: str) -> str:
    """Get the next topic for a content type using round-robin rotation.

    When all topics are exhausted, resets to the beginning (shuffled).
    """
    pool = TOPIC_POOL.get(content_type, TOPIC_POOL["micro_protocol"])
    state = _load_state()
    index = state.get(content_type, 0)

    # Reset if we've used all topics
    if index >= len(pool):
        index = 0
        # Shuffle for variety on repeat
        random.shuffle(pool)

    topic = pool[index]
    state[content_type] = index + 1
    _save_state(state)

    logger.info("Topic assigned [%s] #%d: %s", content_type, index, topic[:50])
    return topic


