async def generate_carousel_deck(custom_topic: Optional[str] = None) -> Tuple[Dict, str, str]:
    """
    Генерирует данные карусели через LLM или fallback-генератор.
    Возвращает: (deck_data, topic_title, post_caption)
    """
    if custom_topic and custom_topic.strip():
        topic_info = {
            "title": custom_topic.strip(),
            "category": "НЕЙРОБИОЛОГИЯ // АРХИВ СССР",
            "focus": custom_topic.strip(),
        }
    else:
        topic_info = get_next_carousel_topic()

    topic_title = topic_info["title"]
    user_prompt = (
        f"Тема карусели: «{topic_title}»\n"
        f"Категория: {topic_info.get('category', 'НЕЙРОБИОЛОГИЯ // АРХИВ')}\n"
        f"Ключевой фокус и тезисы: {topic_info.get('focus', '')}\n\n"
        f"Сгенерируй полный JSON для 5 слайдов и текст caption. "
        f"Напомню: в слайде 4 каждый шаг обязан содержать code вида '01 // ТЕГ' (где ТЕГ — одно слово капсом: ВОДА, ХОЛОД, ДЫХАНИЕ, СОН, ПАМЯТЬ и т.п.)."
    )

    deck_data = None
    post_caption = ""

    # Пробуем вызвать OpenRouter
    if OPENROUTER_API_KEY:
        try:
            model = "meta-llama/llama-3.3-70b-instruct"
            headers = {
                "Authorization": f"Bearer {OPENROUTER_API_KEY}",
                "HTTP-Referer": "https://spectrmind.ru",
                "X-Title": "SpectrMind Carousel Generator",
            }
            client_kwargs = {"timeout": 60.0}
            if PROXY_URL:
                client_kwargs["proxy"] = PROXY_URL

            async with httpx.AsyncClient(**client_kwargs) as client:
                resp = await client.post(
                    "https://openrouter.ai/api/v1/chat/completions",
                    headers=headers,
                    json={
                        "model": model,
                        "messages": [
                            {"role": "system", "content": SYSTEM_PROMPT},
                            {"role": "user", "content": user_prompt},
                        ],
                        "temperature": 0.65,
                        "max_tokens": 2000,
                    },
                )
                if resp.status_code == 200:
                    raw_content = resp.json()["choices"][0]["message"]["content"]
                    # Очищаем от возможных markdown-оберток ```json
                    cleaned = re.sub(r"^```(?:json)?", "", raw_content.strip(), flags=re.MULTILINE)
                    cleaned = re.sub(r"```$", "", cleaned.strip(), flags=re.MULTILINE).strip()
                    parsed = json.loads(cleaned)
                    if "slides" in parsed and len(parsed["slides"]) >= 4:
                        deck_data = parsed
                        post_caption = parsed.get("caption", "")
        except Exception as e:
            logger.warning("LLM carousel generation failed, using structured fallback: %s", e)

    # Если LLM не вернул валидный JSON — используем качественный fallback
    if not deck_data:
        deck_data = _get_fallback_deck(topic_info)
        post_caption = deck_data.get("caption", "")

    # Гарантируем привязку фонового арта мозга на слайд 1
    if "slides" in deck_data and len(deck_data["slides"]) > 0:
        bg_art = "carousel_tool/assets/cyan_brain_bg.jpg"
        if os.path.isfile(bg_art):
            deck_data["slides"][0]["bg_image"] = bg_art

    return deck_data, topic_title, post_caption


