from openai import AsyncOpenAI
import config

_client = None


def get_client() -> AsyncOpenAI:
    global _client
    if _client is None:
        _client = AsyncOpenAI(
            api_key=config.OPENROUTER_API_KEY,
            base_url=config.OPENROUTER_BASE_URL,
            default_headers={
                "HTTP-Referer": "https://spectrmind.ru",
                "X-Title": "SpectrMind Bot",
            },
        )
    return _client


